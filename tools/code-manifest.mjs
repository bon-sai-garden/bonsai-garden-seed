// WHY. Since F-12 (bonsai-garden-sign 1.1.0, 2026-10-21) a seal's address is provenance, never a verdict: a file
// passes wherever its bytes are (the gardener, 2026-10-20: "if the bytes don't change a file should pass integrity
// check regardless of which repo contains it"). One thing the address used to stop is then open, and Mori-shin named
// it: another sealed module, with its sidecar, put in the place of a module that a gate runs by its path. The gate
// cannot see that from the file's own seal, because it does not know which document belongs at which position. Only
// a map knows. The gardener's pick, 2026-10-20 ("2a"): a file's path never fails an integrity check, and every gate
// that runs code checks a sealed manifest. A cut tree has one already (rt's RT-MANIFEST.json, the seed's
// SEED-MANIFEST.json, a package's MANIFEST.json: path and sha256). A living checkout (mono, runtime) gets this one.
//
// WHAT IT IS. A JSON file at the checkout's root, CODE-MANIFEST.json, generated from the tree and sealed like any
// file: one entry per tracked code file (.py .sh .mjs .cjs .js) that carries a v2 seal, its path relative to the
// root and the id its seal carries. Positions to identities, not bytes: the bytes are each file's own seal's, and an
// edit re-sealed keeps its id, so the map moves only when code is added, moved or removed. A gate reads it this way:
// the code at a path runs only when the path is listed, the id at that path is the listed one, and the map's own
// seal holds. A rollback to an older seal of the same document keeps its id and is not stopped here (it was not
// stopped by the address either); a cut's manifest pins bytes and stops it.
//
// A capability, so core (LAYERS.md: would another garden need it? yes); the instances are the checkouts' own files.
//
//   node tools/code-manifest.mjs write --root <checkout>   write <checkout>/CODE-MANIFEST.json; seal it after
//   node tools/code-manifest.mjs check --root <checkout>   the drift gate: exit 1, naming each difference, when the
//                                                           committed map is not what `write` would write now
//
// Tracked files only (git ls-files): a map vouches for the committed tree. A new script is listed once it is
// added to git and the map is written again. Two sidecars beside one file is refused, never chosen between.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { findSidecar, readSidecar } from '../skills/bonsai-garden-sign/lib/sidecar-format.mjs';
import { sidecarGeneration } from '../skills/bonsai-garden-sign/lib/seal-v2.mjs';

export const MANIFEST_NAME = 'CODE-MANIFEST.json';
export const FORMAT = 'bonsai-garden-code-manifest/1';
export const CODE_EXT = /\.(py|sh|mjs|cjs|js)$/;
const NOTE =
  'Generated by bonsai-garden-core tools/code-manifest.mjs; never edited by hand. Which sealed document sits at ' +
  "which path: the gates that run code run it only from here (F-12, 2026-10-21). Bytes are each file's own seal's.";

/** { manifest, refused, unsealed } for the checkout at `root`, from its tracked files. Never writes. */
export function generate(root) {
  const out = execFileSync('git', ['-C', root, 'ls-files', '-z'], { maxBuffer: 256 * 1024 * 1024 });
  const rels = out.toString('utf8').split('\0').filter(Boolean).sort();
  const files = [];
  const refused = [];
  let unsealed = 0;
  for (const rel of rels) {
    if (!CODE_EXT.test(rel) || rel === MANIFEST_NAME) continue;
    const abs = path.join(root, ...rel.split('/'));
    let st;
    try {
      st = fs.lstatSync(abs);
    } catch {
      continue; // tracked, deleted in the working tree: not code that can run
    }
    if (!st.isFile()) continue; // a symlink names someone else's code; its own target is mapped where it lives
    const found = findSidecar(abs);
    if (found.status === 'two-sidecars') {
      refused.push(`${rel}: two sidecars beside one file (${found.paths.map((p) => path.basename(p)).join(', ')})`);
      continue;
    }
    if (found.status !== 'ok') {
      unsealed++;
      continue;
    }
    const { data, error } = readSidecar(found.path);
    if (error || sidecarGeneration(data) !== 'v2' || typeof data.id !== 'string') {
      unsealed++; // a v1 or unreadable seal carries no id to place: not mapped, and the gates say so for it
      continue;
    }
    files.push({ path: rel, id: data.id });
  }
  return { manifest: { format: FORMAT, note: NOTE, files }, refused, unsealed };
}

export const render = (m) => `${JSON.stringify(m, null, 1)}\n`;

/** The differences between a committed map and a generated one, as lines; [] when they agree. */
export function drift(committed, fresh) {
  const a = new Map((committed?.files || []).map((f) => [f.path, f.id]));
  const b = new Map(fresh.files.map((f) => [f.path, f.id]));
  const lines = [];
  if (committed?.format !== FORMAT) lines.push(`format is ${JSON.stringify(committed?.format)}, not ${FORMAT}`);
  for (const [p, id] of b) {
    if (!a.has(p)) lines.push(`not in the map: ${p} (${id})`);
    else if (a.get(p) !== id) lines.push(`${p}: the map says ${a.get(p)}, the seal there says ${id}`);
  }
  for (const [p, id] of a) if (!b.has(p)) lines.push(`in the map, not in the tree: ${p} (${id})`);
  return lines;
}

function main(argv) {
  const verb = argv[0];
  const i = argv.indexOf('--root');
  const root = i >= 0 ? path.resolve(argv[i + 1]) : null;
  if (!['write', 'check'].includes(verb) || !root) {
    console.error('usage: code-manifest.mjs write|check --root <checkout>');
    return 2;
  }
  if (!fs.existsSync(path.join(root, '.git'))) {
    console.error(`${root} is not a git checkout: a code manifest maps a checkout's tracked files`);
    return 2;
  }
  const { manifest, refused, unsealed } = generate(root);
  if (refused.length) {
    for (const r of refused) console.error(`refused: ${r}`);
    return 1;
  }
  const file = path.join(root, MANIFEST_NAME);
  if (verb === 'write') {
    fs.writeFileSync(file, render(manifest));
    console.log(
      `wrote ${file}: ${manifest.files.length} sealed code file(s) mapped, ${unsealed} unsealed or v1 left out. ` +
        'Seal it now: sign.py sign-sidecar, or sign.mjs seal.',
    );
    return 0;
  }
  let committed = null;
  try {
    committed = JSON.parse(fs.readFileSync(file, 'utf8'));
  } catch (err) {
    console.error(`FAIL ${MANIFEST_NAME} at ${root} is missing or unreadable (${err.code || err.message})`);
    return 1;
  }
  const lines = drift(committed, manifest);
  if (!lines.length && fs.readFileSync(file, 'utf8') === render(manifest)) {
    console.log(`ok   ${MANIFEST_NAME}: ${manifest.files.length} sealed code file(s), the map is the tree's`);
    return 0;
  }
  console.error(`FAIL ${MANIFEST_NAME} has drifted from the tree at ${root}:`);
  for (const l of lines.length ? lines : ['the same entries, written differently: write it again']) {
    console.error(`  ${l}`);
  }
  console.error(`  fix: node <core>/tools/code-manifest.mjs write --root ${root}, then seal it`);
  return 1;
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('code-manifest.mjs')) {
  process.exitCode = main(process.argv.slice(2));
}
